from datetime import datetime
from uuid import UUID

from tortoise import fields
from tortoise.models import Model

from .guild import Guild


class MemberActivitySettings(Model):
    id: fields.Field[UUID] = fields.UUIDField(pk=True)
    guild: fields.OneToOneRelation[Guild] = fields.OneToOneField(
        "models.Guild", related_name="member_activity_settings"
    )
    guild_id: int  # column generated by the relation above

    message_channel_ids: fields.Field[list[int]] = fields.JSONField(default=list)
    voice_channel_ids: fields.Field[list[int]] = fields.JSONField(default=list)
    # Categories tracked in full: every text channel inside counts for messages and every voice
    # channel inside counts for voice, on top of the channels listed above.
    tracked_category_ids: fields.Field[list[int]] = fields.JSONField(default=list)


class MemberActivityMessageEvent(Model):
    id: fields.Field[UUID] = fields.UUIDField(pk=True)
    guild: fields.ForeignKeyRelation[Guild] = fields.ForeignKeyField(
        "models.Guild", related_name="member_activity_messages"
    )
    guild_id: int

    member_id: fields.Field[int] = fields.BigIntField()
    channel_id: fields.Field[int] = fields.BigIntField()
    created_at: fields.Field[datetime] = fields.DatetimeField()

    class Meta(Model.Meta):
        indexes: tuple[tuple[str, ...], ...] = (("guild", "member_id", "created_at"),)


class MemberActivityVoiceSession(Model):
    """One continuous stretch of counted voice time, in one channel.

    Same session model as `StaffVoiceSession` (stats_staff): the id is generated in memory when
    the session starts, so every flush can upsert the same row. `ended_at` is deliberately left
    out of every index since it is rewritten on each flush.
    """

    id: fields.Field[UUID] = fields.UUIDField(pk=True)
    guild: fields.ForeignKeyRelation[Guild] = fields.ForeignKeyField(
        "models.Guild", related_name="member_activity_voice_sessions"
    )
    guild_id: int

    member_id: fields.Field[int] = fields.BigIntField()
    channel_id: fields.Field[int] = fields.BigIntField()
    started_at: fields.Field[datetime] = fields.DatetimeField()
    ended_at: fields.Field[datetime] = fields.DatetimeField()

    class Meta(Model.Meta):
        indexes: tuple[tuple[str, ...], ...] = (("guild", "member_id", "started_at"),)


__all__ = ("MemberActivityMessageEvent", "MemberActivitySettings", "MemberActivityVoiceSession")
