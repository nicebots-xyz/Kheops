from datetime import datetime
from enum import StrEnum
from uuid import UUID

from tortoise import fields
from tortoise.models import Model

from .guild import Guild

TITLE_MAX_LENGTH = 256
CONTENT_MAX_LENGTH = 3072
FOOTER_MAX_LENGTH = 512
#: Discord role-select menus cap at 25 options (see absence/AbsenceSettings.allowed_role_ids),
#: but an announcement's own "roles to mention" field is capped lower by the original modal
#: (RoleSelect max_values=10) — kept as-is, not widened.
MAX_ROLES_TO_MENTION = 10


class AnnouncementStatus(StrEnum):
    SCHEDULED = "scheduled"
    SENT = "sent"
    CANCELLED = "cancelled"
    FAILED = "failed"


class AnnounceSettings(Model):
    id: fields.Field[UUID] = fields.UUIDField(pk=True)
    guild: fields.OneToOneRelation[Guild] = fields.OneToOneField("models.Guild", related_name="announce_settings")
    guild_id: int  # column generated by the relation above

    # Who can SCHEDULE an announcement, on top of the admin-always-can baseline (same pattern as
    # AbsenceSettings.allowed_role_ids). Sending INSTANTLY stays admin-only — see
    # src/extensions/announce/logic.py — so this list only ever gates deferred sends.
    allowed_role_ids: fields.Field[list[int]] = fields.JSONField(default=list)


class Announcement(Model):
    id: fields.Field[UUID] = fields.UUIDField(pk=True)
    guild: fields.ForeignKeyRelation[Guild] = fields.ForeignKeyField("models.Guild", related_name="announcements")
    guild_id: int  # column generated by the relation above

    channel_id: fields.Field[int] = fields.BigIntField()

    title: fields.Field[str] = fields.CharField(max_length=TITLE_MAX_LENGTH)
    content: fields.Field[str] = fields.CharField(max_length=CONTENT_MAX_LENGTH)
    footer: fields.Field[str | None] = fields.CharField(max_length=FOOTER_MAX_LENGTH, null=True)  # pyright: ignore[reportAssignmentType]
    role_ids_to_mention: fields.Field[list[int]] = fields.JSONField(default=list)

    # Stored in Postgres rather than on disk: this bot has no durable file storage anywhere (no
    # mounted volume, no object storage) — the database is the only persistence used throughout
    # the codebase, so a blob column keeps this consistent with every other extension instead of
    # introducing a new storage mechanism just for this one field.
    image_data: fields.Field[bytes | None] = fields.BinaryField(null=True)  # pyright: ignore[reportAssignmentType]
    image_filename: fields.Field[str | None] = fields.CharField(max_length=255, null=True)  # pyright: ignore[reportAssignmentType]

    # `None` means "send immediately" (already handled by the time the row exists — see
    # send_announcement) — set to a future datetime to defer to the scheduler loop.
    scheduled_for: fields.Field[datetime | None] = fields.DatetimeField(null=True)  # pyright: ignore[reportAssignmentType]
    status: AnnouncementStatus = fields.CharEnumField(enum_type=AnnouncementStatus, default=AnnouncementStatus.SENT)

    message_id: fields.Field[int | None] = fields.BigIntField(null=True)  # pyright: ignore[reportAssignmentType]
    created_by_id: fields.Field[int] = fields.BigIntField()

    created_at: fields.Field[datetime] = fields.DatetimeField(auto_now_add=True)
    updated_at: fields.Field[datetime] = fields.DatetimeField(auto_now=True)
    sent_at: fields.Field[datetime | None] = fields.DatetimeField(null=True)  # pyright: ignore[reportAssignmentType]

    class Meta(Model.Meta):
        indexes: tuple[tuple[str, ...], ...] = (("guild_id", "status"),)


__all__ = (
    "CONTENT_MAX_LENGTH",
    "FOOTER_MAX_LENGTH",
    "MAX_ROLES_TO_MENTION",
    "TITLE_MAX_LENGTH",
    "AnnounceSettings",
    "Announcement",
    "AnnouncementStatus",
)
